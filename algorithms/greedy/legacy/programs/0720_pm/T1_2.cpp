/*
考虑暴力子任务的结论，可以任意排列一段连续的可以移动的字符。
那么我们把问题转化为：对于一段连续的可以移动的字符，
把他们打成一个包裹放到这段的开头一个字符，对于所有可以移动的字符从包裹中取数最大化匹配次数。

从左到右依次匹配：
    如果此时两个字符串该位置均为固定，则直接统计答案。
    如果此时两个字符串位置有一个不固定，那么让不固定的位置去找包裹中是否有与固定位置相同的字符，
        匹配上去，否则匹配另一个字符。
    如果此时两个字符串均不固定，那么有相同字符任选一个匹配，否则匹配仅有的字符。
对于情况二，如果可以匹配上而不去匹配，那么这个位置上答案少 1，而我们只会多获得一个字符
（甚至还要考虑到放置另一个字符的对其的消耗），对答案的贡献最大为 1。
对于情况三，如果不能匹配那么只有唯一的放置方案，否则不匹配的证明参见情况二，本质等价。
设该位置为 si=ti=0，则若 si=ti更改为 1，那么若答案更优一定存在（不妨设）sj=0 固定，
tj由 1 换为 0 ，则存在一个 k 使得 sk被由 1 换为 0，则此时若 tk原来为 1 则答案一定不会更优，若 tk原来为 0 的话，
因为贪心策略的原因 i<k<j，则此时 tp(k<p≤j) 一定不能为 1，因为 tk已经属于是被强制匹配。
故 tj原来即为 0，与前置条件矛盾。
故贪心策略得证。
*/

#include<bits/stdc++.h>
using namespace std;
const int N = 1e5 + 5;
int T;
int n;
string s, t, u, v;
int a[N][2], b[N][2];
int main() {
	cin >> T;
	for(int ti = 1; ti <= T; ti++) {
		cin >> n;
		cin >> s >> t >> u >> v;
		for(int i = 0; i < n; i++) a[i][0] = a[i][1] = b[i][0] = b[i][1] = 0;
		int beg = 0;
		for(int i = 0; i < n; i++) {
			if(u[i] == '0') continue;
			if(i > 0 && u[i - 1] == '0') beg = i;
			a[beg][s[i] - '0']++;
		}
		beg = 0;
		for(int i = 0; i < n; i++) {
			if(v[i] == '0') continue;
			if(i > 0 && v[i - 1] == '0') beg = i;
			b[beg][t[i] - '0']++;
		}
		int c[2] = {0, 0};
		int d[2] = {0, 0};
		int ans = 0;
		for(int i = 0; i < n; i++) {
			c[0] += a[i][0], c[1] += a[i][1], d[0] += b[i][0], d[1] += b[i][1];
			int o = 0;
			if(u[i] == '0' && v[i] == '0') ans += (s[i] == t[i]);
			else if(u[i] == '0') {
				o = s[i] - '0';
				if(d[o] > 0) ans++, d[o]--;
				else d[1 - o]--;
			} else if(v[i] == '0') {
				o = t[i] - '0';
				if(c[o] > 0) ans++, c[o]--;
				else c[1 - o]--;
			} else {
				if(c[0] > 0 && d[0] > 0) c[0]--, d[0]--, ans++;
				else if(c[1] > 0 && d[1] > 0) c[1]--, d[1]--, ans++;
				else {
					if(c[0] > 0) c[0]--;
					if(c[1] > 0) c[1]--;
					if(d[0] > 0) d[0]--;
					if(d[1] > 0) d[1]--; 
				}
			}
		}
		cout << ans << endl;
	}
	return 0;
}